// 导出辅助函数：获取下一个 quest
export function getNextQuest(currentQuestId) {
  const current = QUESTS.find(q => q.id === currentQuestId);
  if (!current) return null;
  return QUESTS.find(q => q.id === current.unlockedNext);
}
